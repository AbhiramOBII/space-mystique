    <script>
        // Hide loading screen when page is ready
        window.addEventListener('load', function() {
            const loadingScreen = document.getElementById('loading-screen');
            loadingScreen.style.opacity = '0';
            setTimeout(() => {
                loadingScreen.style.display = 'none';
            }, 300);
        });

        // Mobile Menu Functionality
        document.addEventListener('DOMContentLoaded', function() {
            const mobileMenuButton = document.getElementById('mobile-menu-button');
            const mobileMenuClose = document.getElementById('mobile-menu-close');
            const mobileMenu = document.getElementById('mobile-menu');
            const hamburgerIcon = document.getElementById('hamburger-icon');
            const closeIcon = document.getElementById('close-icon');
            const mobileMenuLinks = document.querySelectorAll('.mobile-menu-link');

            // Function to close mobile menu
            function closeMobileMenu() {
                mobileMenu.classList.add('translate-x-full');
                hamburgerIcon.classList.remove('hidden');
                closeIcon.classList.add('hidden');
                document.body.classList.remove('overflow-hidden');
            }

            // Function to open mobile menu
            function openMobileMenu() {
                mobileMenu.classList.remove('translate-x-full');
                hamburgerIcon.classList.add('hidden');
                closeIcon.classList.remove('hidden');
                document.body.classList.add('overflow-hidden');
            }

            // Toggle mobile menu
            mobileMenuButton.addEventListener('click', function() {
                const isOpen = !mobileMenu.classList.contains('translate-x-full');
                
                if (isOpen) {
                    closeMobileMenu();
                } else {
                    openMobileMenu();
                }
            });

            // Close button functionality
            mobileMenuClose.addEventListener('click', closeMobileMenu);

            // Close menu when clicking on links
            mobileMenuLinks.forEach(link => {
                link.addEventListener('click', closeMobileMenu);
            });

            // Close menu when clicking outside
            mobileMenu.addEventListener('click', function(e) {
                if (e.target === mobileMenu) {
                    closeMobileMenu();
                }
            });

            // Smooth scrolling for anchor links
            document.querySelectorAll('a[href^="#"]').forEach(anchor => {
                anchor.addEventListener('click', function (e) {
                    e.preventDefault();
                    const target = document.querySelector(this.getAttribute('href'));
                    if (target) {
                        target.scrollIntoView({
                            behavior: 'smooth',
                            block: 'start'
                        });
                    }
                });
            });

            // Header background on scroll
            let ticking = false;
            function updateHeader() {
                const header = document.querySelector('header');
                if (window.scrollY > 100) {
                    header.classList.add('bg-dark-charcoal');
                    header.classList.remove('bg-dark-charcoal/95');
                } else {
                    header.classList.add('bg-dark-charcoal/95');
                    header.classList.remove('bg-dark-charcoal');
                }
                ticking = false;
            }

            window.addEventListener('scroll', function() {
                if (!ticking) {
                    requestAnimationFrame(updateHeader);
                    ticking = true;
                }
            });
        });

        // Projects Carousel Functionality
        document.addEventListener('DOMContentLoaded', function() {
            const carousel = document.getElementById('projects-carousel');
            const prevBtn = document.getElementById('prev-btn');
            const nextBtn = document.getElementById('next-btn');
            const dots = document.querySelectorAll('.carousel-dot');
            
            let currentIndex = 0;
            const totalSlides = 6;
            
            function getSlideWidth() {
                // Get actual card width including margin
                const cards = carousel.children;
                if (cards.length > 0) {
                    const cardRect = cards[0].getBoundingClientRect();
                    const cardStyle = window.getComputedStyle(cards[0]);
                    const marginRight = parseInt(cardStyle.marginRight) || 24;
                    return cardRect.width + marginRight;
                }
                return window.innerWidth >= 768 ? 408 : 344; // fallback
            }
            
            function getVisibleSlides() {
                const containerWidth = carousel.parentElement.getBoundingClientRect().width;
                const slideWidth = getSlideWidth();
                return Math.floor(containerWidth / slideWidth);
            }
            
            function getMaxIndex() {
                const visibleSlides = getVisibleSlides();
                return Math.max(0, totalSlides - visibleSlides);
            }

            function updateCarousel() {
                const slideWidth = getSlideWidth();
                const translateX = -currentIndex * slideWidth;
                carousel.style.transform = `translateX(${translateX}px)`;
                
                // Update dots
                dots.forEach((dot, index) => {
                    if (index === currentIndex) {
                        dot.classList.remove('bg-warm-grey/30');
                        dot.classList.add('bg-warm-orange');
                    } else {
                        dot.classList.remove('bg-warm-orange');
                        dot.classList.add('bg-warm-grey/30');
                    }
                });
                
                // Update button states
                const maxIndex = getMaxIndex();
                prevBtn.style.opacity = currentIndex === 0 ? '0.5' : '1';
                nextBtn.style.opacity = currentIndex >= maxIndex ? '0.5' : '1';
            }

            function nextSlide() {
                const maxIndex = getMaxIndex();
                if (currentIndex < maxIndex) {
                    currentIndex++;
                } else {
                    currentIndex = 0; // Loop back to start
                }
                updateCarousel();
            }

            function prevSlide() {
                const maxIndex = getMaxIndex();
                if (currentIndex > 0) {
                    currentIndex--;
                } else {
                    currentIndex = maxIndex; // Loop to end
                }
                updateCarousel();
            }

            // Event listeners
            nextBtn.addEventListener('click', nextSlide);
            prevBtn.addEventListener('click', prevSlide);

            // Dot navigation
            dots.forEach((dot, index) => {
                dot.addEventListener('click', () => {
                    const maxIndex = getMaxIndex();
                    currentIndex = Math.min(index, maxIndex);
                    updateCarousel();
                });
            });

            // Auto-play carousel (optional - remove if not wanted)
            let autoPlayInterval = setInterval(nextSlide, 6000);
            
            // Pause auto-play on hover
            carousel.parentElement.addEventListener('mouseenter', () => {
                clearInterval(autoPlayInterval);
            });
            
            carousel.parentElement.addEventListener('mouseleave', () => {
                autoPlayInterval = setInterval(nextSlide, 6000);
            });

            // Handle window resize
            window.addEventListener('resize', () => {
                const maxIndex = getMaxIndex();
                if (currentIndex > maxIndex) {
                    currentIndex = maxIndex;
                }
                updateCarousel();
            });
            
            // Initial setup
            updateCarousel();
        });

    </script>
